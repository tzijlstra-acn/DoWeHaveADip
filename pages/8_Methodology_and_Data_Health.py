# --- Fixtures Status ---
st.header("Demo Fixtures Status")
fixture_files = {
    "bull_market.parquet": "5yr bull market (synthetic GBM, mu=12%, sigma=15%)",
    "crash_and_recovery.parquet": "Bull → 40% crash → recovery (synthetic)",
    "sideways.parquet": "5yr sideways (synthetic GBM, mu=2%, sigma=20%)",
    "demo_fx.parquet": "Stable FX (EUR/USD/CHF, synthetic mean-reverting)",
}

fixture_rows = []
for filename, description in fixture_files.items():
    path = FIXTURES_DIR / filename
    exists = path.exists()
    size_kb = f"{path.stat().st_size / 1024:.1f} KB" if exists else "—"
    last_mod = (
        pd.Timestamp(path.stat().st_mtime, unit="s").strftime("%Y-%m-%d %H:%M")
        if exists
        else "—"
    )
    fixture_rows.append(
        {
            "File": filename,
            "Description": description,
            "Exists": "Yes" if exists else "No — run generate.py",
            "Size": size_kb,
            "Generated": last_mod,
        }
    )

st.dataframe(pd.DataFrame(fixture_rows), use_container_width=True, hide_index=True)

if not all((FIXTURES_DIR / f).exists() for f in fixture_files):
    st.warning(
        "Some fixtures are missing. Run: `uv run python data/fixtures/generate.py`",
        icon="⚠️",
    )

# --- Cache Status ---
st.header("Price Cache Status")
db_path = CACHE_DIR / "prices.duckdb"
if db_path.exists():
    size_mb = db_path.stat().st_size / 1024 / 1024
    st.success(f"Cache database exists ({size_mb:.2f} MB): {db_path}")
    try:
        import duckdb

        conn = duckdb.connect(str(db_path))
        symbols = conn.execute(
            "SELECT symbol, COUNT(*) as n_rows, MAX(dt) as last_dt FROM price_cache GROUP BY symbol ORDER BY symbol"
        ).df()
        conn.close()
        if len(symbols) > 0:
            st.dataframe(symbols, use_container_width=True, hide_index=True)
        else:
            st.info("Cache is empty — data will be fetched on demand.")
    except Exception:
        st.info("Cache database exists but could not be read.")
else:
    st.info("No cache database yet — it will be created when you first load live data.")

