# --- Limitations ---
st.header("Known Limitations")
st.markdown(
    """
    - **Slippage model is flat**: real slippage varies by liquidity and order size.
    - **Tax treatment is simplified**: no wash-sale rules, no tax-loss harvesting.
    - **No dividend recapture timing**: assumes dividends are immediately reinvested.
    - **No bid/ask spread**: uses close prices only.
    - **Survivorship bias**: historical ETF data reflects funds that still exist.
    - **Demo data is synthetic**: GBM is not representative of real market dynamics.
    - **FX rates are spot rates**: actual ETF FX exposure may differ (hedging, settlement).
    """
)

